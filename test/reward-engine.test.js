const {test}=require('node:test');
const assert=require('node:assert/strict');
process.env.USE_MONGODB='false';process.env.JWT_SECRET='test';process.env.JWT_REFRESH_SECRET='test-refresh';
const engine=require('../src/services/reward-engine.service');
const rules=require('../src/services/reward-rule.service');
const users=require('../src/models/user.model');
const health=require('../src/models/health.model');
const wallet=require('../src/models/wallet.model');
test('awards once, preserves snapshots and history through edits and deletion, and finalizes winners',async()=>{
 const user=await users.createUser({name:'Reward member',email:'reward-engine@example.test',passwordHash:'test'});
 const input={title:'Monthly badge',ruleType:'BADGE',audience:'INDIVIDUAL',metric:'STEPS',targetValue:1000,bonusPoints:5};
 const badge=await rules.create(input,user.id,new Date('2026-11-01T00:00:00Z'));
 health.healthRecords.push({id:'record-engine',user_id:user.id,metric_type:'steps',value:1500,source:'health_connect',dataOrigin:'phone',recordingMethod:'automatic',recorded_at:'2026-11-02T08:00:00Z',startTime:'2026-11-02T07:00:00Z',endTime:'2026-11-02T08:00:00Z'});
 await Promise.all([engine.evaluate(new Date('2026-11-03T08:00:00Z')),engine.evaluate(new Date('2026-11-03T08:00:00Z'))]);
 await engine.evaluate(new Date('2026-11-03T08:00:00Z'));
 assert.equal((await wallet.findWallet(user.id)).availablePoints,5);
 assert.equal((await engine.forUser(user.id)).achievements.length,1);
 await rules.update(badge.id,{targetValue:10000,bonusPoints:100},user.id);
 await engine.evaluate(new Date('2026-11-04T08:00:00Z'));
 assert.equal((await engine.forUser(user.id)).competitions[0].targetValue,1000);
 await rules.remove(badge.id);
 assert.equal((await engine.forUser(user.id)).achievements.length,1);
 const leaderboard=await rules.create({...input,title:'Monthly winners',ruleType:'LEADERBOARD',bonusPoints:7,winnersCount:1},user.id);
 await engine.evaluate(new Date('2026-11-04T08:00:00Z'));
 assert.equal((await wallet.findWallet(user.id)).availablePoints,5);
 await engine.evaluate(new Date('2026-12-01T01:00:00Z'));
 assert.equal((await wallet.findWallet(user.id)).availablePoints,12);
 const history=await engine.forUser(user.id);
 assert.equal(history.competitions.find(row=>row.id===`${leaderboard.id}:2026-11-01`).status,'FINAL');
 await engine.evaluate(new Date('2026-12-02T01:00:00Z'));
 assert.equal((await wallet.findWallet(user.id)).availablePoints,12);
});
test('group enrollment is fixed, paused awards stop, and future challenges wait',async()=>{
 const community=require('../src/models/community.model');
 const first=await users.createUser({name:'Group first',email:'first-group-engine@example.test',passwordHash:'test'});
 const second=await users.createUser({name:'Group later',email:'later-group-engine@example.test',passwordHash:'test'});
 community.memoryGroups.push({id:'reward-group',name:'Snapshot group',maxMembers:50,members:[{userId:first.id}]});
 const groupRule=await rules.create({title:'Group badge',ruleType:'BADGE',audience:'GROUP',targetGroupId:'reward-group',metric:'STEPS',targetValue:500,bonusPoints:3},first.id);
 await engine.evaluate(new Date('2026-11-03T08:00:00Z'));
 community.memoryGroups.find(row=>row.id==='reward-group').members.push({userId:second.id});
 health.healthRecords.push({id:'group-record',user_id:first.id,metric_type:'steps',value:600,source:'health_connect',dataOrigin:'phone',recordingMethod:'automatic',recorded_at:'2026-11-04T08:00:00Z',startTime:'2026-11-04T07:00:00Z',endTime:'2026-11-04T08:00:00Z'});
 await rules.update(groupRule.id,{status:'INACTIVE'},first.id);
 await engine.evaluate(new Date('2026-11-05T08:00:00Z'));
 assert.equal((await wallet.findWallet(first.id)).availablePoints,0);
 await rules.update(groupRule.id,{status:'ACTIVE'},first.id);
 await engine.evaluate(new Date('2026-11-05T08:00:00Z'));
 assert.equal((await wallet.findWallet(first.id)).availablePoints,3);
 assert.equal((await wallet.findWallet(second.id)).availablePoints,0);
 assert.ok(!(await engine.forUser(second.id)).competitions.some(row=>row.id.startsWith(groupRule.id)));
 const future=await rules.create({title:'Future timed',ruleType:'CHALLENGE',audience:'INDIVIDUAL',targetUserId:first.id,metric:'STEPS',targetValue:500,period:'DURATION',startDate:'2026-11-10',durationDays:7,bonusPoints:10},first.id);
 await engine.evaluate(new Date('2026-11-05T08:00:00Z'));
 assert.equal((await wallet.findWallet(first.id)).availablePoints,3);
 assert.equal((await engine.forUser(first.id)).competitions.find(row=>row.id.startsWith(future.id)).start,'2026-11-10');
});
